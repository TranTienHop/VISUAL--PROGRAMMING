-- Tao CSDL QuanLyDiem
IF NOT EXISTS (SELECT name FROM sys.databases WHERE name = N'QuanLyDiem')
BEGIN
    CREATE DATABASE QuanLyDiem;
END
GO

USE QuanLyDiem;
GO

IF OBJECT_ID(N'dbo.DiemMon', N'U') IS NOT NULL DROP TABLE dbo.DiemMon;
IF OBJECT_ID(N'dbo.SinhVien', N'U') IS NOT NULL DROP TABLE dbo.SinhVien;
IF OBJECT_ID(N'dbo.Lop', N'U') IS NOT NULL DROP TABLE dbo.Lop;
GO

CREATE TABLE dbo.Lop (
    MaLop VARCHAR(10) NOT NULL PRIMARY KEY,
    TenLop NVARCHAR(100) NOT NULL
);
GO

CREATE TABLE dbo.SinhVien (
    MaSV VARCHAR(10) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    NgaySinh DATETIME NOT NULL,
    GioiTinh NVARCHAR(3) NOT NULL,
    MaLop VARCHAR(10) NOT NULL,
    CONSTRAINT FK_SinhVien_Lop FOREIGN KEY (MaLop) REFERENCES dbo.Lop(MaLop)
);
GO

CREATE TABLE dbo.DiemMon (
    MaDiem INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaSV VARCHAR(10) NOT NULL,
    TenMon NVARCHAR(100) NOT NULL,
    SoTinChi INT NOT NULL CONSTRAINT CK_DiemMon_SoTinChi CHECK (SoTinChi BETWEEN 1 AND 6),
    Diem DECIMAL(4,2) NOT NULL CONSTRAINT CK_DiemMon_Diem CHECK (Diem >= 0 AND Diem <= 10),
    CONSTRAINT FK_DiemMon_SinhVien FOREIGN KEY (MaSV) REFERENCES dbo.SinhVien(MaSV)
);
GO

